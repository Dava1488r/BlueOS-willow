#!/usr/bin/env python3
"""
Generates BlueOS logo assets from tools/blueos_logo.py into media/logo/:
  blueos_logo.svg                      - reference artwork (light background colors)
  preview-{light,dark}.png             - quick look
  drawable{,-night}/blueos_logo.xml    - VectorDrawable in the system (Monet) colors,
                                         copied into Settings / SetupWizard patches
  drawable{,-night}/blueos_logo_halo.xml, drawable/blueos_logo_halo_anim.xml
                                       - the same with the falling halo animation (SetupWizard)
  drawable{,-night}/blueos_logo_shutdown.xml, drawable/blueos_logo_shutdown_{off,reboot}.xml
                                       - power off (halo disappears) / reboot (halo spins),
                                         copied into the SystemUI patch (ShutdownUi)
  recovery/res-*/images/logo_image{,_switch}.png - recovery header (fixed brand colors)
"""

import math
import os

import cairo

from blueos_logo import (ACCENT_ON_DARK, ACCENT_ON_LIGHT, HALO_ANGLE, HALO_RX, HALO_RY,
                         HALO_STROKE, TEXT_ON_DARK, TEXT_ON_LIGHT, Logo)

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "media", "logo")


def hexc(c):
    return "#%02X%02X%02X" % c


def rgb(c):
    return tuple(v / 255 for v in c)


def draw_logo(ctx, logo, text, accent):
    ctx.set_source_rgb(*rgb(text))
    logo.draw_text(ctx, "blue")
    ctx.set_source_rgb(*rgb(accent))
    logo.draw_text(ctx, "os")
    logo.draw_halo(ctx)


def write_svg(logo):
    x0, y0, x1, y1 = logo.bounds()
    pad = 2
    vb = (x0 - pad, y0 - pad, x1 - x0 + 2 * pad, y1 - y0 + 2 * pad)
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb[0]:.2f} {vb[1]:.2f} {vb[2]:.2f} {vb[3]:.2f}">
  <path fill="{hexc(TEXT_ON_LIGHT)}" d="{Logo.svg_path(logo.blue)}"/>
  <path fill="{hexc(ACCENT_ON_LIGHT)}" d="{Logo.svg_path(logo.os)}"/>
  <ellipse cx="{logo.halo_cx:.2f}" cy="{logo.halo_cy:.2f}" rx="{HALO_RX}" ry="{HALO_RY}" fill="none"
    stroke="{hexc(ACCENT_ON_LIGHT)}" stroke-width="{HALO_STROKE}" transform="rotate({HALO_ANGLE} {logo.halo_cx:.2f} {logo.halo_cy:.2f})"/>
</svg>
"""
    with open(os.path.join(OUT, "blueos_logo.svg"), "w") as f:
        f.write(svg)


def write_vector(logo, night, animated=False, shutdown=False):
    """VectorDrawable in Monet colors: primary = tone 40 (light) / 80 (dark), like the bootanim.
    animated: blueos_logo_halo.xml for write_halo_animation() - extra room above the halo,
    which starts hidden above the logo (group "halo", path "halo_path").
    shutdown: blueos_logo_shutdown.xml for write_shutdown_animations() - the halo is visible,
    with a little room above it to bob (group "halo", path "halo_path", spinning group
    "halo_spin")."""
    x0, y0, x1, y1 = logo.bounds()
    pad = 1
    top = pad + (HALO_DROP_ROOM if animated or shutdown else 0)
    dx, dy = -(x0 - pad), -(y0 - top)
    w, h = x1 - x0 + 2 * pad, y1 - y0 + pad + top
    mode = "dark" if night else "light"
    cx, cy = logo.halo_cx + dx, logo.halo_cy + dy
    halo = (f"M{cx + HALO_RX:.2f},{cy:.2f} A{HALO_RX},{HALO_RY} 0 1,1 {cx - HALO_RX:.2f},{cy:.2f} "
            f"A{HALO_RX},{HALO_RY} 0 1,1 {cx + HALO_RX:.2f},{cy:.2f} Z")
    halo_xml = f"""    <group
        android:pivotX="{cx:.2f}"
        android:pivotY="{cy:.2f}"
        android:rotation="{HALO_ANGLE}">
        <path
            android:strokeColor="@android:color/system_primary_{mode}"
            android:strokeWidth="{HALO_STROKE}"
            android:pathData="{halo}" />
    </group>
"""
    if animated:
        halo_xml = halo_xml.replace(
            "        <path\n",
            '        <path\n            android:name="halo_path"\n'
            '            android:strokeAlpha="0"\n')
        halo_xml = (f'    <group\n        android:name="halo"\n'
                    f'        android:translateY="{-HALO_DROP}">\n'
                    + "".join("    " + line + "\n" for line in halo_xml.splitlines())
                    + "    </group>\n")
    elif shutdown:
        halo_xml = halo_xml.replace(
            "    <group\n", '    <group\n        android:name="halo_spin"\n', 1).replace(
            "        <path\n", '        <path\n            android:name="halo_path"\n')
        halo_xml = ('    <group\n        android:name="halo">\n'
                    + "".join("    " + line + "\n" for line in halo_xml.splitlines())
                    + "    </group>\n")
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- BlueOS logo. Generated by vendor/blueos/tools/make-logo-assets.py - do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{w * 1.25:.1f}dp"
    android:height="{h * 1.25:.1f}dp"
    android:viewportWidth="{w:.2f}"
    android:viewportHeight="{h:.2f}">
    <path
        android:fillColor="@android:color/system_on_surface_{mode}"
        android:pathData="{Logo.svg_path(logo.blue, dx, dy)}" />
    <path
        android:fillColor="@android:color/system_primary_{mode}"
        android:pathData="{Logo.svg_path(logo.os, dx, dy)}" />
{halo_xml}</vector>
"""
    d = os.path.join(OUT, "drawable-night" if night else "drawable")
    os.makedirs(d, exist_ok=True)
    name = ("blueos_logo_halo.xml" if animated else
            "blueos_logo_shutdown.xml" if shutdown else "blueos_logo.xml")
    with open(os.path.join(d, name), "w") as f:
        f.write(xml)


# Halo animation (setup wizard welcome): the halo falls in from above the logo, fading in,
# lands with a small overshoot and then keeps bobbing. Units = logo viewport units.
HALO_DROP = 14
HALO_DROP_ROOM = 3
HALO_BOB = 1.5


def write_halo_animation():
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- BlueOS logo with the halo animation. Generated by vendor/blueos/tools/make-logo-assets.py. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:drawable="@drawable/blueos_logo_halo">
    <target android:name="halo">
        <aapt:attr name="android:animation">
            <set android:ordering="sequentially">
                <objectAnimator
                    android:duration="750"
                    android:interpolator="@android:interpolator/overshoot"
                    android:propertyName="translateY"
                    android:startOffset="300"
                    android:valueFrom="{-HALO_DROP}"
                    android:valueTo="0"
                    android:valueType="floatType" />
                <objectAnimator
                    android:duration="1200"
                    android:interpolator="@android:interpolator/accelerate_decelerate"
                    android:propertyName="translateY"
                    android:repeatCount="infinite"
                    android:repeatMode="reverse"
                    android:valueFrom="0"
                    android:valueTo="{-HALO_BOB}"
                    android:valueType="floatType" />
            </set>
        </aapt:attr>
    </target>
    <target android:name="halo_path">
        <aapt:attr name="android:animation">
            <objectAnimator
                android:duration="450"
                android:propertyName="strokeAlpha"
                android:startOffset="300"
                android:valueFrom="0"
                android:valueTo="1"
                android:valueType="floatType" />
        </aapt:attr>
    </target>
</animated-vector>
"""
    with open(os.path.join(OUT, "drawable", "blueos_logo_halo_anim.xml"), "w") as f:
        f.write(xml)


# Power off / reboot (SystemUI ShutdownUi). Halos never fly away - like in the game they just
# disappear. Off: the halo bobs once, then fades out where it is (ShutdownUi fades the rest out
# afterwards). Reboot: the halo spins around its own axis until the screen goes off - the boot
# animation then lets it fall back in.


def write_shutdown_animations():
    head = """<?xml version="1.0" encoding="utf-8"?>
<!-- BlueOS {what}. Generated by vendor/blueos/tools/make-logo-assets.py. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:drawable="@drawable/blueos_logo_shutdown">
"""
    off = head.format(what="power off: the halo disappears") + f"""    <target android:name="halo">
        <aapt:attr name="android:animation">
            <set android:ordering="sequentially">
                <objectAnimator
                    android:duration="350"
                    android:interpolator="@android:interpolator/accelerate_decelerate"
                    android:propertyName="translateY"
                    android:startOffset="150"
                    android:valueFrom="0"
                    android:valueTo="{-HALO_BOB}"
                    android:valueType="floatType" />
                <objectAnimator
                    android:duration="350"
                    android:interpolator="@android:interpolator/accelerate_decelerate"
                    android:propertyName="translateY"
                    android:valueFrom="{-HALO_BOB}"
                    android:valueTo="0"
                    android:valueType="floatType" />
            </set>
        </aapt:attr>
    </target>
    <target android:name="halo_path">
        <aapt:attr name="android:animation">
            <objectAnimator
                android:duration="600"
                android:interpolator="@android:interpolator/accelerate_quad"
                android:propertyName="strokeAlpha"
                android:startOffset="850"
                android:valueFrom="1"
                android:valueTo="0"
                android:valueType="floatType" />
        </aapt:attr>
    </target>
</animated-vector>
"""
    reboot = head.format(what="reboot: the halo spins") + """    <target android:name="halo_spin">
        <aapt:attr name="android:animation">
            <objectAnimator
                android:duration="700"
                android:interpolator="@android:interpolator/accelerate_decelerate"
                android:propertyName="scaleX"
                android:repeatCount="infinite"
                android:repeatMode="reverse"
                android:valueFrom="1"
                android:valueTo="-1"
                android:valueType="floatType" />
        </aapt:attr>
    </target>
</animated-vector>
"""
    for name, xml in (("blueos_logo_shutdown_off.xml", off),
                      ("blueos_logo_shutdown_reboot.xml", reboot)):
        with open(os.path.join(OUT, "drawable", name), "w") as f:
            f.write(xml)


def write_preview(logo, dark):
    scale = 6
    x0, y0, x1, y1 = logo.bounds()
    w, h = int((x1 - x0 + 20) * scale), int((y1 - y0 + 20) * scale)
    surf = cairo.ImageSurface(cairo.FORMAT_RGB24, w, h)
    ctx = cairo.Context(surf)
    ctx.set_source_rgb(*((0, 0, 0) if dark else (1, 1, 1)))
    ctx.paint()
    ctx.scale(scale, scale)
    ctx.translate(-x0 + 10, -y0 + 10)
    draw_logo(ctx, logo, TEXT_ON_DARK if dark else TEXT_ON_LIGHT,
              ACCENT_ON_DARK if dark else ACCENT_ON_LIGHT)
    surf.write_to_png(os.path.join(OUT, "preview-%s.png" % ("dark" if dark else "light")))


# Recovery: same layout as LineageOS' header (pill outline, emblem, "RECOVERY" label),
# drawn in xxhdpi coordinates (768x480) and scaled per density.
DENSITIES = {"mdpi": 1 / 3, "hdpi": 0.5, "xhdpi": 2 / 3, "xxhdpi": 1.0, "xxxhdpi": 4 / 3}
RECOVERY_LABEL = (0x9F, 0xD0, 0xFF)


def rounded_pill(ctx, x, y, w, h):
    r = h / 2
    ctx.new_path()
    ctx.arc(x + r, y + r, r, math.pi / 2, 3 * math.pi / 2)
    ctx.arc(x + w - r, y + r, r, -math.pi / 2, math.pi / 2)
    ctx.close_path()


def write_recovery(logo):
    for name, k in DENSITIES.items():
        for switch in (False, True):
            w, h = round(768 * k), round(480 * k)
            surf = cairo.ImageSurface(cairo.FORMAT_RGB24, w, h)
            ctx = cairo.Context(surf)
            ctx.set_source_rgb(0, 0, 0)
            ctx.paint()
            ctx.scale(w / 768, h / 480)

            ctx.set_source_rgb(*rgb(ACCENT_ON_LIGHT))
            ctx.set_line_width(6)
            rounded_pill(ctx, 5, 132, 758, 216)
            ctx.stroke()

            # emblem: the logo, ~330 px wide, centered in the pill
            x0, y0, x1, y1 = logo.bounds()
            s = 330 / (x1 - x0)
            ctx.save()
            ctx.translate(384 - (x0 + x1) / 2 * s, 240 - (y0 + y1) / 2 * s)
            ctx.scale(s, s)
            draw_logo(ctx, logo, TEXT_ON_DARK, ACCENT_ON_DARK)
            ctx.restore()

            label, size, tracking = "RECOVERY", 34, 0.3
            lw = logo.text_width(label, size, tracking)
            ctx.set_source_rgb(*rgb(RECOVERY_LABEL))
            logo.fill(ctx, logo.outline(label, 384 - lw / 2, 422, size, tracking))

            if switch:
                # "R" (current: recovery) diamond with a dot, "F" (fastboot) triangle
                ctx.save()
                ctx.translate(113, 238)
                ctx.rotate(math.pi / 4)
                ctx.rectangle(-30, -30, 60, 60)
                ctx.restore()
                ctx.set_source_rgb(*rgb(ACCENT_ON_DARK))
                ctx.fill_preserve()
                ctx.set_source_rgb(*rgb(ACCENT_ON_LIGHT))
                ctx.set_line_width(6)
                ctx.set_line_join(cairo.LINE_JOIN_ROUND)
                ctx.stroke()
                ctx.set_source_rgb(0x06 / 255, 0x22 / 255, 0x3F / 255)
                rw = logo.text_width("R", 34)
                logo.fill(ctx, logo.outline("R", 113 - rw / 2, 250, 34))
                ctx.set_source_rgb(1, 1, 1)
                ctx.arc(113, 314, 6, 0, 2 * math.pi)
                ctx.fill()

                ctx.set_line_width(6)
                ctx.move_to(655, 197)
                ctx.line_to(702, 278)
                ctx.line_to(608, 278)
                ctx.close_path()
                ctx.stroke()
                fw = logo.text_width("F", 32)
                logo.fill(ctx, logo.outline("F", 655 - fw / 2, 266, 32))

            d = os.path.join(OUT, "recovery", "res-" + name, "images")
            os.makedirs(d, exist_ok=True)
            surf.write_to_png(os.path.join(d, "logo_image_switch.png" if switch else "logo_image.png"))


def write_recovery_loop(logo, frames=30):
    """Recovery "working" animation (installing / wiping), replaces LineageOS' loop*.png:
    the logo with a bright arc running around the halo once per loop."""
    import blueos_logo as bl
    length = Logo.halo_length()
    for name, k in DENSITIES.items():
        size = round(600 * k)
        d = os.path.join(OUT, "recovery", "res-" + name, "images")
        os.makedirs(d, exist_ok=True)
        x0, y0, x1, y1 = logo.bounds()
        s = 0.7 * size / (x1 - x0)
        for i in range(frames):
            surf = cairo.ImageSurface(cairo.FORMAT_RGB24, size, size)
            ctx = cairo.Context(surf)
            ctx.set_source_rgb(0, 0, 0)
            ctx.paint()
            ctx.translate(size / 2 - (x0 + x1) / 2 * s, size / 2 - (y0 + y1) / 2 * s)
            ctx.scale(s, s)
            ctx.set_source_rgb(*rgb(TEXT_ON_DARK))
            logo.draw_text(ctx, "blue")
            ctx.set_source_rgb(*rgb(ACCENT_ON_DARK))
            logo.draw_text(ctx, "os")
            # dim halo + a bright arc (30% of it) moving clockwise
            ctx.set_source_rgb(*rgb(ACCENT_ON_LIGHT))
            logo.draw_halo(ctx)
            ctx.save()
            ctx.translate(logo.halo_cx, logo.halo_cy)
            ctx.rotate(math.radians(bl.HALO_ANGLE))
            ctx.scale(bl.HALO_RX, bl.HALO_RY)
            ctx.new_path()
            ctx.arc(0, 0, 1, 0, 2 * math.pi)
            ctx.restore()
            ctx.set_line_width(bl.HALO_STROKE)
            ctx.set_line_cap(cairo.LINE_CAP_ROUND)
            arc = 0.3 * length
            ctx.set_dash([arc, length - arc], -length * i / frames)
            ctx.set_source_rgb(*rgb(ACCENT_ON_DARK))
            ctx.stroke()
            ctx.set_dash([])
            surf.write_to_png(os.path.join(d, "loop%05d.png" % i))


def main():
    os.makedirs(OUT, exist_ok=True)
    logo = Logo()
    write_recovery_loop(logo)
    write_svg(logo)
    write_vector(logo, night=False)
    write_vector(logo, night=True)
    write_vector(logo, night=False, animated=True)
    write_vector(logo, night=True, animated=True)
    write_halo_animation()
    write_vector(logo, night=False, shutdown=True)
    write_vector(logo, night=True, shutdown=True)
    write_shutdown_animations()
    write_preview(logo, dark=False)
    write_preview(logo, dark=True)
    write_recovery(logo)
    print("logo bounds:", ["%.1f" % v for v in logo.bounds()],
          "halo center: %.1f,%.1f" % (logo.halo_cx, logo.halo_cy))


if __name__ == "__main__":
    main()
