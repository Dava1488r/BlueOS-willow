#!/usr/bin/env python3
"""
BlueOS system fonts (Settings > Display > Font, applied after a reboot).

LineageOS' /product/etc/fonts_customization.xml defines the families the system UI uses
(google-sans*, google-sans-flex*, variable-* of the Material 3 type scale) on top of
Google Sans Flex. For every font below this writes a copy of it into
fonts/etc/fonts_customization_<id>.xml where those families point at that font, plus a
"blueos-<id>" family per font for the previews in the picker. frameworks/base (BlueOS
patch in SystemFonts) loads the copy named by persist.sys.blueos.font.

Also writes fonts/Android.bp (font files -> /product/fonts, xmls -> /product/etc/blueos).
Re-run after a repo sync that changes LineageOS' file.
"""

import copy
import os
import xml.etree.ElementTree as ET

TOP = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
LINEAGE_XML = os.path.join(TOP, "packages/overlays/Lineage/fonts/etc/fonts_customization.xml")
FONTS = os.path.join(TOP, "vendor/blueos/fonts")

# id -> (name in the picker, files). files: {weight: file} for static fonts (optional
# "italic" dict), or ("variable", file, min_wght, max_wght). Order = order in the picker.
CHOICES = [
    ("nunito", "Nunito", {"dir": "nunito", "variable": ("Nunito-VF.ttf", 200, 1000)}),
    ("googlesansflex", "Google Sans Flex", None),  # LineageOS' own file
    ("mplusrounded1c", "M PLUS Rounded 1c", {
        "dir": "mplusrounded1c",
        "static": {400: "MPLUSRounded1c-Regular.ttf", 500: "MPLUSRounded1c-Medium.ttf",
                   700: "MPLUSRounded1c-Bold.ttf"}}),
    ("comfortaa", "Comfortaa", {"dir": "comfortaa", "variable": ("Comfortaa-VF.ttf", 300, 700)}),
    ("manrope", "Manrope", {"dir": "manrope", "variable": ("Manrope-VF.ttf", 200, 800)}),
    # installed by external/google-fonts/rubik (PRODUCT_PACKAGES in config/blueos.mk)
    ("rubik", "Rubik", {
        "static": {400: "Rubik-Regular.ttf", 500: "Rubik-Medium.ttf", 700: "Rubik-Bold.ttf"},
        "italic": {400: "Rubik-Italic.ttf", 500: "Rubik-MediumItalic.ttf",
                   700: "Rubik-BoldItalic.ttf"}}),
]

# Lock screen clock keeps Google Sans Flex: the default clock animates its weight axis.
KEEP = {"google-sans-clock", "google-sans-flex-clock"}

# BlueOS "Halo" lock screen clock (SystemUI DefaultClockProvider): Outfit, the logo font
CLOCK = {"dir": "outfit", "variable": ("Outfit-VF.ttf", 100, 900)}


def nearest(files, weight):
    # 600 (semi-bold) -> bold
    return files[min(files, key=lambda w: (abs(w - weight), -w))]


def rewrite_font(font, spec):
    weight = int(font.get("weight", "400"))
    italic = font.get("style") == "italic"
    for axis in list(font):
        font.remove(axis)
    if "variable" in spec:
        name, lo, hi = spec["variable"]
        font.text = name
        ET.SubElement(font, "axis", {"tag": "wght", "stylevalue": str(max(lo, min(hi, weight)))})
    else:
        files = spec["italic"] if italic and "italic" in spec else spec["static"]
        font.text = nearest(files, weight)


def preview_family(fid, spec):
    fam = ET.Element("family", {"customizationType": "new-named-family", "name": "blueos-" + fid})
    font = ET.SubElement(fam, "font", {"weight": "400", "style": "normal"})
    if spec is None:
        font.text = "GoogleSansFlex-Regular.ttf"
    elif "variable" in spec:
        font.text = spec["variable"][0]
        ET.SubElement(font, "axis", {"tag": "wght", "stylevalue": "400"})
    else:
        font.text = spec["static"][400]
    return fam


def write_xml(fid, spec, base):
    root = copy.deepcopy(base)
    if spec is not None:
        for fam in root.findall("family"):
            if fam.get("name") in KEEP:
                continue
            for font in fam.findall("font"):
                rewrite_font(font, spec)
    root.append(ET.Comment(" BlueOS: font previews in Settings > Display > Font "))
    for pid, _, pspec in CHOICES:
        root.append(preview_family(pid, pspec))
    root.append(ET.Comment(" BlueOS: Halo lock screen clock "))
    clock = preview_family("clock", CLOCK)
    clock.find("font").clear()  # one variable font, the clock sets the weight itself
    clock.find("font").text = CLOCK["variable"][0]
    root.append(clock)
    ET.indent(root, space="    ")
    os.makedirs(os.path.join(FONTS, "etc"), exist_ok=True)
    path = os.path.join(FONTS, "etc", "fonts_customization_%s.xml" % fid)
    with open(path, "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n'
                "<!-- Generated by vendor/blueos/tools/make-fonts.py from LineageOS'\n"
                "     fonts_customization.xml - do not edit. -->\n")
        f.write(ET.tostring(root, encoding="unicode"))
        f.write("\n")


def write_bp():
    out = ["//", "// BlueOS system fonts. Generated by tools/make-fonts.py - do not edit.", "//", "",
           "package {", '    default_applicable_licenses: ["vendor_blueos_fonts_license"],', "}", "",
           "license {", '    name: "vendor_blueos_fonts_license",',
           '    license_kinds: ["SPDX-license-identifier-OFL"],',
           "    license_text: ["]
    specs = [spec for _, _, spec in CHOICES if spec and "dir" in spec] + [CLOCK]
    dirs = [spec["dir"] for spec in specs]
    out += ['        "%s/OFL.txt",' % d for d in dirs]
    out += ["    ],", "}", ""]
    for d in dirs:
        spec = next(s for s in specs if s.get("dir") == d)
        files = [spec["variable"][0]] if "variable" in spec else sorted(set(spec["static"].values()))
        for f in files:
            out += ["prebuilt_font {", '    name: "%s",' % f, '    src: "%s/%s",' % (d, f),
                    "    product_specific: true,", "}", ""]
    for fid, _, _ in CHOICES:
        out += ["prebuilt_etc {", '    name: "fonts_customization_%s.xml",' % fid,
                '    src: "etc/fonts_customization_%s.xml",' % fid,
                '    sub_dir: "blueos",', "    product_specific: true,", "}", ""]
    with open(os.path.join(FONTS, "Android.bp"), "w") as f:
        f.write("\n".join(out))


def main():
    base = ET.parse(LINEAGE_XML).getroot()
    for fid, _, spec in CHOICES:
        write_xml(fid, spec, base)
    write_bp()
    print("modules:", " ".join(
        [f for _, _, s in CHOICES if s and "dir" in s
         for f in ([s["variable"][0]] if "variable" in s else sorted(set(s["static"].values())))]
        + ["fonts_customization_%s.xml" % fid for fid, _, _ in CHOICES]))


if __name__ == "__main__":
    main()
