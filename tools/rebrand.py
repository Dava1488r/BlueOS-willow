#!/usr/bin/env python3
"""Generates resource overlays that replace "LineageOS" with "BlueOS" in user-visible strings.

usage: python3 vendor/blueos/tools/rebrand.py [device]   (from the source root, after one full build:
       it reads out/target/product/<device>/module-info.json to know which apps are installed;
       device = the argument, else $TARGET_DEVICE from `breakfast`, else the only one built)

For every installed app it scans res/values and res/values-ru string files and writes
vendor/blueos/overlay/<same res path>/blueos_rebrand.xml with the rewritten strings.
Re-run after `repo sync` so new or changed strings are picked up.
"""
import glob
import json
import os
import re
import sys


def device():
    if len(sys.argv) > 1:
        return sys.argv[1]
    if os.environ.get("TARGET_DEVICE"):
        return os.environ["TARGET_DEVICE"]
    built = [os.path.basename(os.path.dirname(p)) for p in glob.glob("out/target/product/*/module-info.json")]
    if len(built) != 1:
        sys.exit("which device? python3 vendor/blueos/tools/rebrand.py <device> (built: %s)" % ", ".join(built))
    return built[0]


PRODUCT_OUT = "out/target/product/%s/" % device()
OUT_JSON = PRODUCT_OUT + "module-info.json"
OVERLAY = "vendor/blueos/overlay"
OLD, NEW = "LineageOS", "BlueOS"
LOCALES = ("values", "values-ru")
# Strings that keep the LineageOS name on purpose: the credit for the project BlueOS is based on,
# and anything about anonymous statistics, which really are sent to the LineageOS project.
# (services_* metrics strings are written by hand in overlay/.../SetupWizard/.../blueos_strings.xml)
KEEP = {"lineagelicense_title", "anonymous_statistics_summary", "anonymous_statistics_warning",
        "services_help_improve_cm", "services_metrics_label"}
SKIP_PATHS = ("packages/apps/Updater", "packages/apps/Car/", "packages/apps/TvSettings",
              "/tests/", "/test/", "/debug/")
STRING_FILE = re.compile(r"(^|_)strings\.xml$|^cm_strings\.xml$")
ELEMENT = re.compile(r"<(string|string-array|plurals)\b([^>]*)>(.*?)</\1>", re.S)
NAME = re.compile(r'\bname="([^"]+)"')


def installed_app_dirs():
    info = json.load(open(OUT_JSON))
    dirs = set()
    for m in info.values():
        if "APPS" not in m.get("class", []):
            continue
        if not any(p.startswith(PRODUCT_OUT) for p in m.get("installed", [])):
            continue
        dirs.update(m.get("path", []))
    dirs.add("lineage-sdk/lineage/res")  # framework-like resource package (lineageos.platform)
    return sorted(dirs)


def rebrand_file(path):
    text = re.sub(r"<!--.*?-->", "", open(path, encoding="utf-8").read(), flags=re.S)
    out = []
    for m in ELEMENT.finditer(text):
        whole, attrs = m.group(0), m.group(2)
        name = NAME.search(attrs)
        if OLD in m.group(3) and name and name.group(1) not in KEEP:
            out.append(whole.replace(OLD, NEW))
    return out


def main():
    for old in glob.glob(f"{OVERLAY}/**/blueos_rebrand.xml", recursive=True):
        os.remove(old)
    res_dirs = set()
    for app_dir in installed_app_dirs():
        res_dirs.update(glob.glob(f"{app_dir}/**/res", recursive=True))
    total = 0
    for res_dir in sorted(res_dirs):
            if any(s in res_dir + "/" for s in SKIP_PATHS):
                continue
            for loc in LOCALES:
                elements = []
                for f in sorted(glob.glob(f"{res_dir}/{loc}/*.xml")):
                    if STRING_FILE.search(os.path.basename(f)):
                        elements += rebrand_file(f)
                if not elements:
                    continue
                dst = f"{OVERLAY}/{res_dir}/{loc}/blueos_rebrand.xml"
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                with open(dst, "w", encoding="utf-8") as fh:
                    fh.write('<?xml version="1.0" encoding="utf-8"?>\n'
                             "<!-- Generated by vendor/blueos/tools/rebrand.py, do not edit. -->\n"
                             '<resources xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2">\n')
                    for e in elements:
                        fh.write("    " + e + "\n")
                    fh.write("</resources>\n")
                total += len(elements)
                print(f"{len(elements):3d}  {dst}")
    print("total strings:", total)


if __name__ == "__main__":
    main()
